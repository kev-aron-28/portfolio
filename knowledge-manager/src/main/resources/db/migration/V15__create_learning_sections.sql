CREATE TABLE learning_section (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tree_id BIGINT NOT NULL REFERENCES learning_tree(id) ON DELETE CASCADE,
    parent_id BIGINT,
    title VARCHAR(120) NOT NULL,
    UNIQUE (tree_id, id),
    FOREIGN KEY (tree_id, parent_id) REFERENCES learning_section(tree_id, id),
    CHECK (parent_id < id)
);

ALTER TABLE learning_node ADD COLUMN section_id BIGINT;
ALTER TABLE learning_node
    ADD FOREIGN KEY (tree_id, section_id) REFERENCES learning_section(tree_id, id);

CREATE INDEX learning_section_parent ON learning_section(tree_id, parent_id);
CREATE INDEX learning_node_section ON learning_node(tree_id, section_id);
