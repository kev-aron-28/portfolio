CREATE TABLE learning_tree (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(120) NOT NULL
);

CREATE TABLE learning_node (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tree_id BIGINT NOT NULL REFERENCES learning_tree(id),
    title VARCHAR(120) NOT NULL,
    kind VARCHAR(12) NOT NULL CHECK (kind IN ('TOPIC', 'PRACTICE', 'PROJECT', 'MASTERY')),
    criterion TEXT NOT NULL,
    prompt TEXT NOT NULL,
    unlocked BOOLEAN NOT NULL DEFAULT FALSE,
    completed_on DATE,
    evidence TEXT,
    next_review_on DATE,
    UNIQUE (tree_id, id)
);

CREATE UNIQUE INDEX learning_one_mastery ON learning_node(tree_id) WHERE kind = 'MASTERY';

CREATE TABLE learning_edge (
    tree_id BIGINT NOT NULL,
    node_id BIGINT NOT NULL,
    prerequisite_id BIGINT NOT NULL,
    required BOOLEAN NOT NULL,
    PRIMARY KEY (node_id, prerequisite_id),
    FOREIGN KEY (tree_id, node_id) REFERENCES learning_node(tree_id, id),
    FOREIGN KEY (tree_id, prerequisite_id) REFERENCES learning_node(tree_id, id),
    CHECK (prerequisite_id < node_id)
);

CREATE TABLE learning_review (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    node_id BIGINT NOT NULL REFERENCES learning_node(id),
    reviewed_on DATE NOT NULL,
    rating INTEGER NOT NULL CHECK (rating BETWEEN 0 AND 5),
    next_review_on DATE NOT NULL
);

CREATE TABLE learning_focus (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    node_id BIGINT NOT NULL REFERENCES learning_node(id),
    activity VARCHAR(12) NOT NULL CHECK (activity IN ('STUDY', 'PRACTICE', 'REVIEW')),
    started_at TIMESTAMP WITH TIME ZONE NOT NULL,
    ended_at TIMESTAMP WITH TIME ZONE,
    CHECK (ended_at >= started_at)
);

CREATE UNIQUE INDEX learning_one_running_focus ON learning_focus ((1)) WHERE ended_at IS NULL;
